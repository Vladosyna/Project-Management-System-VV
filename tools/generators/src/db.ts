// Generator for packages/db migrations (ocs-db-migration). Protected zone: arch/ branches only.
// With --table it writes a client-data table built like every business table (02-architecture §4):
// client_id, visibility, archived_at, RLS for staff and clients, no DELETE grant, Drizzle definition, RLS test.
import { camel, words } from './names.ts';
import type { Change, Plan } from './plan.ts';

const MIGRATIONS = 'packages/db/migrations';

/** The next migration number after the existing `NNNN_name.up.sql` files. */
export function nextMigrationNumber(existing: readonly string[]): string {
  const numbers = existing.map((f) => Number(f.split('_')[0])).filter(Number.isInteger);
  return String(Math.max(0, ...numbers) + 1).padStart(4, '0');
}

export function migrationPlan(name: string, number: string, table?: string): Plan {
  const file = `${number}_${words(name, 'Migration').join('_')}`;
  const header = `-- ${file} — generated by \`pnpm gen:migration\`. Additive and reversible (ocs-db-migration);
-- never edit a migration once it is on main (CI pr-rules).`;
  if (table === undefined) {
    return {
      permissionsChanged: false,
      changes: [
        { kind: 'create', file: `${MIGRATIONS}/${file}.up.sql`, content: `${header}\n` },
        { kind: 'create', file: `${MIGRATIONS}/${file}.down.sql`, content: `-- Reverts ${file}.\n` },
      ],
      next: [
        `Write the change in ${file}.up.sql and its exact reverse in ${file}.down.sql.`,
        'Mirror new columns in packages/db/src/schema.ts (schema-drift test); new client-data table: use --table.',
      ],
    };
  }

  const ws = words(table, 'Table');
  const t = ws.join('_');
  const id = camel(ws);
  return {
    permissionsChanged: false,
    changes: [
      {
        kind: 'create',
        file: `${MIGRATIONS}/${file}.up.sql`,
        content: `${header}
-- ${t}: client data (02-architecture §4). Staff see all rows; a client sees its own rows marked
-- visibility = 'client'; partners see nothing until a policy links rows to their assigned jobs or sites.
CREATE TABLE ${t} (
  id          uuid PRIMARY KEY,
  client_id   uuid NOT NULL,
  visibility  text NOT NULL DEFAULT 'internal' CHECK (visibility IN ('internal', 'client')),
  created_at  timestamptz NOT NULL DEFAULT now(),
  archived_at timestamptz
);
CREATE INDEX ${t}_client ON ${t} (client_id);

ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;
CREATE POLICY ${t}_internal ON ${t} FOR ALL TO ocs_app
  USING (app.is_internal()) WITH CHECK (app.is_internal());
CREATE POLICY ${t}_client_read ON ${t} FOR SELECT TO ocs_app
  USING (app.actor_kind() = 'client' AND visibility = 'client' AND client_id = ANY (app.client_ids()));
-- No DELETE: archive with archived_at (SOP-DEL-02 "never delete").
GRANT SELECT, INSERT, UPDATE ON ${t} TO ocs_app;
`,
      },
      {
        kind: 'create',
        file: `${MIGRATIONS}/${file}.down.sql`,
        content: `-- Reverts ${file}.\nDROP TABLE ${t};\n`,
      },
      {
        kind: 'append',
        file: 'packages/db/src/schema.ts',
        text: `
/** Migration ${number}. Client data: RLS in the migration; archive, never delete. */
export const ${id} = pgTable('${t}', {
  id: uuid('id').primaryKey(),
  clientId: uuid('client_id').notNull(),
  visibility: text('visibility', { enum: ['internal', 'client'] })
    .notNull()
    .default('internal'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  archivedAt: timestamp('archived_at', { withTimezone: true }),
});`,
      },
      { kind: 'append', file: 'packages/db/src/index.ts', text: `export { ${id} } from './schema.ts';` },
      rlsTest(t, id),
    ],
    next: [
      `Add the business columns to ${file}.up.sql and to ${id} in schema.ts (the schema-drift test compares them).`,
      `Keep the RLS cases in packages/db/src/__tests__/${t}.rls.int.test.ts; add a partner policy and case if partners need rows.`,
      'Protected zone: arch/ branch and architect review.',
    ],
  };
}

function rlsTest(t: string, id: string): Change {
  return {
    kind: 'create',
    file: `packages/db/src/__tests__/${t}.rls.int.test.ts`,
    content: `// ${t} row-level security — generated by \`pnpm gen:migration\` (02-architecture §4, 04-testing §3).
import { randomUUID } from 'node:crypto';
import { afterAll, beforeAll, expect, inject, it } from 'vitest';
import { createTestDatabase, type TestDatabase } from '@ocs/testing';
import { createDatabase, inActorTransaction, migrateUp, ${id}, type Database, type DbActor } from '../index.ts';

const clientA = randomUUID();
const clientB = randomUUID();
const staff: DbActor = { id: randomUUID(), kind: 'staff', clientIds: [] };
const userOfA: DbActor = { id: randomUUID(), kind: 'client', clientIds: [clientA] };
const userOfB: DbActor = { id: randomUUID(), kind: 'client', clientIds: [clientB] };
const partnerOfA: DbActor = { id: randomUUID(), kind: 'partner', clientIds: [clientA] };
let testDb: TestDatabase;
let database: Database;

const visibleTo = (actor: DbActor) =>
  inActorTransaction(database.db, actor, async (tx) => (await tx.select().from(${id})).map((r) => r.clientId));

beforeAll(async () => {
  testDb = await createTestDatabase(inject('postgresUrl'));
  database = createDatabase(testDb.url);
  await migrateUp(database.pool);
  await inActorTransaction(database.db, staff, async (tx) => {
    await tx.insert(${id}).values([
      { id: randomUUID(), clientId: clientA, visibility: 'client' },
      { id: randomUUID(), clientId: clientA, visibility: 'internal' },
      { id: randomUUID(), clientId: clientB, visibility: 'internal' },
    ]);
  });
});

afterAll(async () => {
  await database.close();
  await testDb.drop();
});

it('staff see every row', async () => {
  expect(await visibleTo(staff)).toHaveLength(3);
});

it('a client sees only its own rows marked for clients', async () => {
  expect(await visibleTo(userOfA)).toEqual([clientA]);
  expect(await visibleTo(userOfB)).toEqual([]);
});

it('a partner sees nothing until a partner policy exists', async () => {
  expect(await visibleTo(partnerOfA)).toEqual([]);
});

it('a client cannot write', async () => {
  await expect(
    inActorTransaction(database.db, userOfA, (tx) =>
      tx.insert(${id}).values({ id: randomUUID(), clientId: clientA, visibility: 'client' }),
    ),
  ).rejects.toThrow();
});
`,
  };
}
