// Generator for apps/web screens (ocs-ui-screen): page, route, EN + 中文 title, Playwright check.
import { camel, quote, words } from './names.ts';
import type { Plan } from './plan.ts';

/** Marker lines the screen generator inserts above. */
export const SCREEN_MARKERS = {
  imports: '// gen:screen-imports',
  routes: '// gen:screens',
  catalog: '// gen:screen-titles',
  e2e: '// gen:screens',
} as const;

export function screenPlan(route: string, title: string, titleZh: string): Plan {
  const ws = words(route, 'Route');
  if (!title.trim() || !titleZh.trim()) {
    throw new Error('Give the screen title in both languages: --title "…" --title-zh "…"');
  }
  const key = `${camel(ws)}.title`;
  const component = `${camel(['', ...ws])}Page`;
  const path = `/${route}`;
  return {
    permissionsChanged: false,
    changes: [
      {
        kind: 'create',
        file: `apps/web/src/pages/${route}.tsx`,
        content: `// ${path} — generated by \`pnpm gen:screen ${route}\`. Layout and wording follow the mockup in
// docs/ocs/reference/mockups; data comes from typed queries; every string is an i18n key (ocs-ui-screen).
import { Card, PageHeader, useI18n } from '@ocs/ui';

export function ${component}() {
  const { t } = useI18n();
  return (
    <>
      <PageHeader eyebrow={\`/ \${t('${key}')}\`} title={t('${key}')} />
      <Card>
        <p>{t('page.empty')}</p>
      </Card>
    </>
  );
}
`,
      },
      {
        kind: 'insert',
        file: 'apps/web/src/routes.tsx',
        marker: SCREEN_MARKERS.imports,
        text: `import { ${component} } from './pages/${route}.tsx';`,
      },
      {
        kind: 'insert',
        file: 'apps/web/src/routes.tsx',
        marker: SCREEN_MARKERS.routes,
        text: `  '${path}': ${component},`,
      },
      {
        kind: 'insert',
        file: 'packages/i18n/src/catalog/en.ts',
        marker: SCREEN_MARKERS.catalog,
        text: `  '${key}': ${quote(title.trim())},`,
      },
      {
        kind: 'insert',
        file: 'packages/i18n/src/catalog/zh.ts',
        marker: SCREEN_MARKERS.catalog,
        text: `  '${key}': ${quote(titleZh.trim())},`,
      },
      {
        kind: 'insert',
        file: 'tools/e2e/tests/smoke.spec.ts',
        marker: SCREEN_MARKERS.e2e,
        text: `  { path: '${path}', heading: ${quote(title.trim())} },`,
      },
    ],
    next: [
      `Build ${path} from its mockup in apps/web/src/pages/${route}.tsx; add the screen to NAV if the mockup has it.`,
      `Have a Chinese-speaking colleague check the 中文 title in packages/i18n/src/catalog/zh.ts.`,
      `Check it in the browser: pnpm e2e (the smoke test opens every generated screen).`,
    ],
  };
}
