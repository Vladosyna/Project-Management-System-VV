// Generators for packages/core: module, command, query, rule (02-architecture §3, ocs-new-module, ocs-sop-rule).
// Output must pass `pnpm verify` unchanged — `pnpm gen:selftest` proves it in CI.
import { assertModule, assertPermissionKey, camel, sentence, words } from './names.ts';
import type { Change, Plan } from './plan.ts';

/** Generated permissions.ts files keep this line; gen:command and gen:query add entries above it. */
export const PERMISSIONS_MARKER = '// gen:permissions';
const PERMISSION_IMPORT = "import { permission } from '../kernel/index.ts';\n";

export interface AccessOptions {
  /** Override the derived `<module>.<object>.<action>` key. */
  readonly key?: string | undefined;
  /** Plain-English line for the permission matrix. */
  readonly description?: string | undefined;
  /** Roles that hold the permission. Default: none (reserved) — deny by default until someone decides. */
  readonly roles?: readonly string[] | undefined;
}

const dir = (module: string): string => `packages/core/${module}`;
const quote = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

export function modulePlan(module: string, purpose: string): Plan {
  assertModule(module);
  if (!purpose.trim()) throw new Error('Give the module a one-line purpose');
  return {
    permissionsChanged: false,
    changes: [
      {
        kind: 'create',
        file: `${dir(module)}/index.ts`,
        content: `// ${module} — ${purpose.trim()}
// Public API: other modules and apps may import only what this file exports (02-architecture §2).
export { ${module}Permissions } from './permissions.ts';
`,
      },
      {
        kind: 'create',
        file: `${dir(module)}/permissions.ts`,
        content: `// ${module} permissions — one entry per command and query, with the roles that hold it.
// \`pnpm gen:matrix\` renders them into docs/ocs/permission-matrix.md.
export const ${module}Permissions = {
  ${PERMISSIONS_MARKER} — \`pnpm gen:command\` and \`pnpm gen:query\` add entries above this line.
};
`,
      },
      { kind: 'append', file: 'packages/core/permissions/all.ts', text: `import '../${module}/index.ts';` },
    ],
    next: [
      `packages/core/permissions/all.ts changed: protected zone, so this needs an arch/ branch and architect review.`,
      `Add the first command: pnpm gen:command ${module} <verb-noun>`,
    ],
  };
}

function permissionChanges(
  module: string,
  id: string,
  key: string,
  description: string,
  roles: readonly string[],
) {
  const file = `${dir(module)}/permissions.ts`;
  return [
    { kind: 'ensure', file, line: PERMISSION_IMPORT, before: 'export const' },
    {
      kind: 'insert',
      file,
      marker: PERMISSIONS_MARKER,
      text: `  ${id}: permission(${quote(key)}, {
    description: ${quote(description)},
    roles: [${roles.map(quote).join(', ')}],
  }),`,
    },
  ] satisfies Change[];
}

const roleNote = (roles: readonly string[]): string[] =>
  roles.length === 0
    ? ['Nobody holds the new permission yet: set its roles in permissions.ts, then pnpm gen:matrix.']
    : [];

export function commandPlan(module: string, verbNoun: string, options: AccessOptions = {}): Plan {
  assertModule(module);
  const ws = words(verbNoun, 'Command');
  if (ws.length < 2) throw new Error(`Command "${verbNoun}": verb-noun, e.g. set-eta`);
  const [verb = '', ...noun] = ws;
  const id = camel(ws);
  const object = camel(noun);
  const key = options.key ?? `${module}.${object}.${verb}`;
  assertPermissionKey(key, module);
  const description = options.description ?? sentence(ws);
  const roles = options.roles ?? [];
  return {
    permissionsChanged: true,
    changes: [
      ...permissionChanges(module, id, key, description, roles),
      {
        kind: 'append',
        file: `${dir(module)}/index.ts`,
        text: `export { ${id} } from './commands/${verbNoun}.ts';`,
      },
      {
        kind: 'create',
        file: `${dir(module)}/commands/${verbNoun}.ts`,
        content: `// ${key} — generated by \`pnpm gen:command ${module} ${verbNoun}\`. Fill in the input, the change and the
// audit record. SOP rules go in ../rules (pnpm gen:rule), table access in ../repository.ts (02-architecture §3).
import { z } from 'zod';
import { defineCommand } from '../../kernel/index.ts';
import { ${module}Permissions } from '../permissions.ts';

export const ${id} = defineCommand({
  name: ${quote(key)},
  permission: ${module}Permissions.${id},
  input: z.object({ id: z.uuid() }),
  describe: (i) => \`${description} \${i.id}\`,
  handle: (_ctx, i) =>
    Promise.resolve({
      result: { id: i.id },
      audit: { objectType: ${quote(object)}, objectId: i.id, clientId: null, before: null, after: null },
    }),
});
`,
      },
      {
        kind: 'create',
        file: `${dir(module)}/__tests__/${verbNoun}.int.test.ts`,
        content: `// ${key} — generated by \`pnpm gen:command\`. Keep the guard cases; add the acceptance criterion as
// its own case before you change the handler (04-testing §1).
import { randomUUID } from 'node:crypto';
import { afterAll, beforeAll, describe, expect, inject, it } from 'vitest';
import { aStaffActor, countRows, createTestDatabase, type TestDatabase } from '@ocs/testing';
import { Forbidden, openTestKernel, ValidationFailed, type TestKernel } from '../../kernel/index.ts';
import { ${id} } from '../commands/${verbNoun}.ts';

const allowed = aStaffActor();
const other = aStaffActor();
const audited = async () => countRows(testDb.url, 'audit_event WHERE command = $1', [${id}.name]);
let testDb: TestDatabase;
let t: TestKernel;

beforeAll(async () => {
  testDb = await createTestDatabase(inject('postgresUrl'));
  t = await openTestKernel(testDb.url);
  t.grant(allowed, ${id}.permission);
});

afterAll(async () => {
  await t.close();
  await testDb.drop();
});

describe(${quote(key)}, () => {
  it('refuses an actor without the permission and records nothing', async () => {
    await expect(t.kernel.execute(${id}, other, { id: randomUUID() }, 'test')).rejects.toBeInstanceOf(Forbidden);
    expect(await audited()).toBe(0);
  });

  it('refuses invalid input', async () => {
    await expect(t.kernel.execute(${id}, allowed, { id: 'not-a-uuid' }, 'test')).rejects.toBeInstanceOf(
      ValidationFailed,
    );
  });

  it('records exactly one audit event', async () => {
    await t.kernel.execute(${id}, allowed, { id: randomUUID() }, 'test');
    expect(await audited()).toBe(1);
  });
});
`,
      },
    ],
    next: [
      `Write the acceptance-criterion test in ${dir(module)}/__tests__/${verbNoun}.int.test.ts, then the handler.`,
      ...roleNote(roles),
    ],
  };
}

export function queryPlan(module: string, noun: string, options: AccessOptions = {}): Plan {
  assertModule(module);
  const ws = words(noun, 'Query');
  const id = camel(ws);
  const key = options.key ?? `${module}.${id}.read`;
  assertPermissionKey(key, module);
  const description = options.description ?? `Read ${ws.join(' ')}`;
  const roles = options.roles ?? [];
  return {
    permissionsChanged: true,
    changes: [
      ...permissionChanges(module, id, key, description, roles),
      {
        kind: 'append',
        file: `${dir(module)}/index.ts`,
        text: `export { ${id} } from './queries/${noun}.ts';`,
      },
      {
        kind: 'create',
        file: `${dir(module)}/queries/${noun}.ts`,
        content: `// ${key} — generated by \`pnpm gen:query ${module} ${noun}\`. Read through ../repository.ts; RLS limits the
// rows to what the actor may see. Queries run read-only (02-architecture §3).
import { z } from 'zod';
import { defineQuery } from '../../kernel/index.ts';
import { ${module}Permissions } from '../permissions.ts';

export const ${id} = defineQuery({
  name: ${quote(key)},
  permission: ${module}Permissions.${id},
  input: z.object({}),
  handle: () => Promise.resolve<{ id: string }[]>([]),
});
`,
      },
      {
        kind: 'create',
        file: `${dir(module)}/__tests__/${noun}.int.test.ts`,
        content: `// ${key} — generated by \`pnpm gen:query\`. Add the acceptance criterion and, for client data, the
// own-client / other-client / internal cases (04-testing §3).
import { afterAll, beforeAll, describe, expect, inject, it } from 'vitest';
import { aStaffActor, createTestDatabase, type TestDatabase } from '@ocs/testing';
import { Forbidden, openTestKernel, type TestKernel } from '../../kernel/index.ts';
import { ${id} } from '../queries/${noun}.ts';

const allowed = aStaffActor();
const other = aStaffActor();
let testDb: TestDatabase;
let t: TestKernel;

beforeAll(async () => {
  testDb = await createTestDatabase(inject('postgresUrl'));
  t = await openTestKernel(testDb.url);
  t.grant(allowed, ${id}.permission);
});

afterAll(async () => {
  await t.close();
  await testDb.drop();
});

describe(${quote(key)}, () => {
  it('refuses an actor without the permission', async () => {
    await expect(t.kernel.read(${id}, other, {})).rejects.toBeInstanceOf(Forbidden);
  });

  it('answers an actor with the permission', async () => {
    expect(await t.kernel.read(${id}, allowed, {})).toEqual([]);
  });
});
`,
      },
    ],
    next: [
      `Write the acceptance-criterion test in ${dir(module)}/__tests__/${noun}.int.test.ts, then the handler.`,
      ...roleNote(roles),
    ],
  };
}

export function rulePlan(module: string, ruleKey: string, cite: string, sopVersion: string): Plan {
  assertModule(module);
  const ws = words(ruleKey, 'Rule');
  if (!/^\S.*§\s?\d/.test(cite)) throw new Error(`--cite "${cite}": the clause, e.g. "SOP-DEL-01 §8"`);
  if (!/^\d+\.\d+$/.test(sopVersion)) throw new Error(`--sop-version "${sopVersion}": e.g. 1.3`);
  const id = camel(ws);
  const check = camel(['check', ...ws]);
  const rules = `${dir(module)}/rules`;
  return {
    permissionsChanged: false,
    changes: [
      {
        kind: 'create',
        file: `${rules}/${ruleKey}.config.ts`,
        content: `// ${cite} — ${sentence(ws).toLowerCase()}. The numbers, item codes and lists of the clause live here;
// the evaluator reads only this config. A new SOP version updates this file (sop-index.md).
export const ${id}Rule = {
  cite: ${quote(cite)},
  sopVersion: ${quote(sopVersion)},
  /** Example parameter: replace with what the clause names. */
  limit: 5,
} as const;
`,
      },
      {
        kind: 'create',
        file: `${rules}/${ruleKey}.ts`,
        content: `// ${cite} — evaluator. Reads only ./${ruleKey}.config.ts; refuses with RuleViolation citing the clause.
import { RuleViolation } from '../../kernel/index.ts';
import { ${id}Rule } from './${ruleKey}.config.ts';

export interface ${camel(['', ...ws])}Input {
  readonly value: number;
}

export function ${check}(input: ${camel(['', ...ws])}Input): void {
  if (input.value > ${id}Rule.limit) {
    throw new RuleViolation(${id}Rule.cite, \`\${String(input.value)} is above \${String(${id}Rule.limit)}\`);
  }
}
`,
      },
      {
        kind: 'create',
        file: `${rules}/__tests__/${ruleKey}.examples.test.ts`,
        content: `// ${cite} — examples: input → expected decision. Include the boundary cases (exactly at the limit,
// one over, N/A without a reason …) — ocs-sop-rule §3.
import { describe, expect, it } from 'vitest';
import { RuleViolation } from '../../../kernel/index.ts';
import { ${check} } from '../${ruleKey}.ts';
import { ${id}Rule } from '../${ruleKey}.config.ts';

const examples = [
  { input: { value: 5 }, decision: 'allowed' },
  { input: { value: 6 }, decision: 'blocked' },
] as const;

describe(\`\${${id}Rule.cite} ${ws.join(' ')}\`, () => {
  it.each(examples)('$input.value → $decision', ({ input, decision }) => {
    const run = () => {
      ${check}(input);
    };
    if (decision === 'allowed') expect(run).not.toThrow();
    else expect(run).toThrow(RuleViolation);
  });
});
`,
      },
    ],
    next: [
      `Quote the clause in your plan, replace the example parameter and examples, then call ${check} from the command.`,
    ],
  };
}
